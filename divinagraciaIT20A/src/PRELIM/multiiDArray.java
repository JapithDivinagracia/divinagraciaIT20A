
package PRELIM;


public class multiiDArray {
     public static void main(String[] args) {
        int marks [][] ={ 
           
                  {11,12,13},
                  {22,23,24},
                  {33,34,35},
        };
        
                  
                 for (int i = 0; i < marks.length; i++){
                 for (int j = 0; j < marks[i].length; j++){
                 System.out.print(marks[i][j] + " ");
                 }
                 System.out.println();
                        
}
        }
}
